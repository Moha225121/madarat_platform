<?php

namespace App\Storage;

use PDO;
use RuntimeException;

/** Shared by the Laravel migration and the standalone, pre-deployment rescue. */
final class StoredFileSchema
{
    public const MIGRATION = '2026_10_28_000001_create_stored_files_table';

    public const LOCK = 20261028;

    public static function create(PDO $pdo): void
    {
        $pgsql = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME) === 'pgsql';
        $id = $pgsql ? 'bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
        $binary = $pgsql ? 'bytea' : 'BLOB';
        $json = $pgsql ? 'jsonb' : 'TEXT';
        $length = $pgsql ? 'octet_length(contents)' : 'length(contents)';
        $hashCheck = $pgsql ? ", CONSTRAINT stored_files_hash_check CHECK (encode(sha256(contents), 'hex') = sha256)" : '';
        $pdo->exec("CREATE TABLE stored_files (
            id $id,
            disk varchar(20) NOT NULL,
            path varchar(512) NOT NULL,
            original_name varchar(255) NOT NULL,
            mime_type varchar(255) NOT NULL,
            size bigint NOT NULL,
            sha256 char(64) NOT NULL,
            access varchar(16) NOT NULL,
            owner_user_id bigint NULL,
            contents $binary NOT NULL,
            created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
            updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT stored_files_disk_path_unique UNIQUE (disk, path),
            CONSTRAINT stored_files_owner_user_id_foreign FOREIGN KEY (owner_user_id) REFERENCES users(id) ON DELETE SET NULL,
            CONSTRAINT stored_files_disk_check CHECK (disk IN ('public', 'documents', 'preserved')),
            CONSTRAINT stored_files_access_check CHECK (access = CASE WHEN disk = 'public' THEN 'public' ELSE 'private' END),
            CONSTRAINT stored_files_size_check CHECK (size >= 0 AND (size > 0 OR disk = 'preserved') AND size <= 67108864 AND size = $length)
            $hashCheck
        )");
        $pdo->exec('CREATE INDEX stored_files_sha256_index ON stored_files (sha256)');
        $pdo->exec("CREATE TABLE stored_file_import_runs (
            id char(64) PRIMARY KEY,
            instance_tag varchar(64) NOT NULL,
            manifest $json NOT NULL,
            created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
        )");
    }

    public static function fingerprint(PDO $pdo): string
    {
        $sql = "SELECT c.relname, a.attname, format_type(a.atttypid,a.atttypmod) AS type, a.attnotnull,
            pg_get_expr(d.adbin,d.adrelid) AS default_value, a.attidentity
            FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
            WHERE n.nspname='public' AND c.relname IN ('stored_files','stored_file_import_runs')
            AND a.attnum>0 AND NOT a.attisdropped ORDER BY c.relname,a.attnum";
        $columns = $pdo->query($sql)->fetchAll(PDO::FETCH_ASSOC);
        $constraints = $pdo->query("SELECT c.relname, con.conname, con.contype, con.convalidated,
            pg_get_constraintdef(con.oid) AS definition FROM pg_constraint con
            JOIN pg_class c ON c.oid=con.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace
            WHERE n.nspname='public' AND c.relname IN ('stored_files','stored_file_import_runs')
            ORDER BY c.relname,con.conname")->fetchAll(PDO::FETCH_ASSOC);
        foreach ($constraints as &$constraint) {
            // pg_dump restores this IN-list with casts on each element instead
            // of the whole varchar array. Accept only that exact equivalent
            // expression; a changed value/check/FK/index still fails verification.
            if ($constraint['relname'] === 'stored_files' && $constraint['conname'] === 'stored_files_disk_check'
                && $constraint['definition'] === "CHECK (((disk)::text = ANY (ARRAY[('public'::character varying)::text, ('documents'::character varying)::text, ('preserved'::character varying)::text])))") {
                $constraint['definition'] = "CHECK (((disk)::text = ANY ((ARRAY['public'::character varying, 'documents'::character varying, 'preserved'::character varying])::text[])))";
            }
        }
        unset($constraint);
        $indexes = $pdo->query("SELECT tablename,indexname,indexdef FROM pg_indexes WHERE schemaname='public'
            AND tablename IN ('stored_files','stored_file_import_runs') ORDER BY tablename,indexname")->fetchAll(PDO::FETCH_ASSOC);

        return hash('sha256', json_encode([$columns, $constraints, $indexes], JSON_THROW_ON_ERROR));
    }

    public static function verify(PDO $pdo): void
    {
        if ($pdo->getAttribute(PDO::ATTR_DRIVER_NAME) !== 'pgsql') {
            throw new RuntimeException('Production storage verification requires PostgreSQL.');
        }
        // Filled from the verified PostgreSQL 18.6 migration, including types,
        // nullability/defaults, constraints/FKs and indexes; drift fails closed.
        $expected = 'e50901e8ee3af25be3e9b83b988d907b873bcd33368d9ab0b929105f4457e032';
        if (self::fingerprint($pdo) !== $expected) {
            throw new RuntimeException('Stored-file schema differs from the reviewed migration.');
        }
    }

    public static function verifyWithLedger(PDO $pdo): void
    {
        self::verify($pdo);
        $query = $pdo->prepare('SELECT count(*) FROM migrations WHERE migration=?');
        $query->execute([self::MIGRATION]);
        if ((int) $query->fetchColumn() !== 1) {
            throw new RuntimeException('Stored-file migration ledger is inconsistent.');
        }
    }

    public static function prepareWithLedger(PDO $pdo): bool
    {
        if ($pdo->getAttribute(PDO::ATTR_DRIVER_NAME) !== 'pgsql' || $pdo->inTransaction()) {
            throw new RuntimeException('Requires a direct PostgreSQL connection outside a transaction.');
        }
        $pdo->beginTransaction();
        try {
            $pdo->exec('SELECT pg_advisory_xact_lock(190733, '.self::LOCK.')');
            $check = $pdo->prepare('SELECT count(*) FROM migrations WHERE migration = ?');
            $check->execute([self::MIGRATION]);
            $records = (int) $check->fetchColumn();
            $tables = (int) $pdo->query("SELECT count(*) FROM information_schema.tables WHERE table_schema='public'
                AND table_name IN ('stored_files','stored_file_import_runs')")->fetchColumn();
            if ($records === 0 && $tables === 0) {
                self::create($pdo);
                self::verify($pdo);
                $batch = (int) $pdo->query('SELECT COALESCE(MAX(batch),0)+1 FROM migrations')->fetchColumn();
                $insert = $pdo->prepare('INSERT INTO migrations (migration,batch) VALUES (?,?)');
                $insert->execute([self::MIGRATION, $batch]);
                $created = true;
            } elseif ($records === 1 && $tables === 2) {
                self::verify($pdo);
                $created = false;
            } else {
                throw new RuntimeException('Schema and migration ledger conflict; manual review required.');
            }
            $pdo->commit();

            return $created;
        } catch (\Throwable $error) {
            $pdo->rollBack();
            throw $error;
        }
    }
}
